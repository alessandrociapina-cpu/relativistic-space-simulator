/** Vetores 3D em 64 bits (UA, UA/dia) para as efemérides. */
export type Vec3 = readonly [number, number, number];

export const add = (a: Vec3, b: Vec3): Vec3 => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
export const sub = (a: Vec3, b: Vec3): Vec3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
export const scale = (a: Vec3, k: number): Vec3 => [a[0] * k, a[1] * k, a[2] * k];
export const dot = (a: Vec3, b: Vec3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
export const norm = (a: Vec3) => Math.hypot(a[0], a[1], a[2]);
export const lerp = (a: Vec3, b: Vec3, w: number): Vec3 => add(a, scale(sub(b, a), w));

export function cross(a: Vec3, b: Vec3): Vec3 {
  return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
}

/** Ângulo entre vetores sem acos (preciso também para ângulos pequenos). */
export const angle = (a: Vec3, b: Vec3) => Math.atan2(norm(cross(a, b)), dot(a, b));
